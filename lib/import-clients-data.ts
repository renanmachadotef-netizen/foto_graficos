function parseDate(dateStr: string): { date: Date | null; day: number | null; month: number | null } {
  if (!dateStr || !dateStr.trim()) return { date: null, day: null, month: null };

  const parts = dateStr.trim().split("/");
  if (parts.length === 3) {
    const day = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10);
    let year = parseInt(parts[2], 10);

    if (isNaN(day) || isNaN(month)) return { date: null, day: null, month: null };

    if (year > 2050) {
      year = 1980;
    }

    const d = new Date(year, month - 1, day);
    return {
      date: isNaN(d.getTime()) ? null : d,
      day: day >= 1 && day <= 31 ? day : null,
      month: month >= 1 && month <= 12 ? month : null,
    };
  }

  return { date: null, day: null, month: null };
}

export async function importLegacyClientsIntoDatabase(targetTenantId: "FOTOGRAFICOS" | "PURABRASIL" = "FOTOGRAFICOS") {
  const lines = RAW_CLIENTS_CSV.trim().split("\n");
  const rows = lines.slice(1);

  console.log(`[Import] Limpando duplicatas e sincronizando ${rows.length} clientes únicos para ${targetTenantId}...`);

  // 1. Remove non-transactional duplicates to ensure clean 1-to-1 sync
  await prisma.client.deleteMany({
    where: {
      tenantId: targetTenantId,
      quotes: { none: {} },
      transactions: { none: {} },
    },
  });

  let count = 0;
  let birthdayCount = 0;

  for (const row of rows) {
    if (!row.trim()) continue;

    const cols = row.split(";");
    const name = cols[0]?.trim();
    if (!name) continue;

    const code = cols[2]?.trim() || null;
    const rawBirthDate = cols[4]?.trim() || "";
    const document = cols[5]?.trim() || null;
    const address = cols[6]?.trim() || null;
    const gender = cols[7]?.trim() || "M";
    const phone = cols[8]?.trim() || null;
    const email = cols[9]?.trim() || null;
    const status = cols[12]?.trim() || "Ativo";

    const { date, day, month } = parseDate(rawBirthDate);
    if (day && month) birthdayCount++;

    // Check if client already exists (e.g. preserved due to quotes/transactions)
    const existing = await prisma.client.findFirst({
      where: {
        tenantId: targetTenantId,
        OR: [
          ...(code ? [{ code }] : []),
          { name },
        ],
      },
    });

    if (existing) {
      await prisma.client.update({
        where: { id: existing.id },
        data: {
          code: code || existing.code,
          document: document || existing.document,
          address: address || existing.address,
          gender: gender || existing.gender,
          phone: phone || existing.phone,
          email: email || existing.email,
          birthDate: date || existing.birthDate,
          birthDay: day || existing.birthDay,
          birthMonth: month || existing.birthMonth,
          status,
        },
      });
    } else {
      await prisma.client.create({
        data: {
          tenantId: targetTenantId,
          name,
          code,
          document: document && document.length > 3 ? document : null,
          address: address && address.length > 3 ? address : null,
          gender,
          phone,
          email: email && email.includes("@") ? email : null,
          birthDate: date,
          birthDay: day,
          birthMonth: month,
          status,
        },
      });
    }

    count++;
  }

  console.log(`[Import] ✅ Concluído com sucesso: ${count} clientes únicos sincronizados (${birthdayCount} com aniversários).`);
  return { count, birthdayCount };
}
